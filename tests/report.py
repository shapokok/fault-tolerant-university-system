"""Merges the two JUnit files, writes the summary and docs/test_plan.md (criterion = test docstring).
Exit code 1 if any test failed."""
import os
import sys
import time
import xml.etree.ElementTree as ET

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "results", "endterm")
SUITES = [("unit", "tests_unit.xml"), ("integration", "tests_integration.xml")]

merged = ET.Element("testsuites")
rows, totals = [], {}
for suite, name in SUITES:
    path = os.path.join(OUT, name)
    if not os.path.exists(path):
        print(f"missing {path}")
        sys.exit(1)
    root = ET.parse(path).getroot()
    for ts in root.iter("testsuite"):
        ts.set("name", suite)
        merged.append(ts)
        for tc in ts.iter("testcase"):
            outcome = "FAIL" if tc.find("failure") is not None or tc.find("error") is not None else \
                "SKIP" if tc.find("skipped") is not None else "PASS"
            prop = tc.find("properties/property[@name='criterion']")
            rows.append((suite, tc.get("classname").split(".")[-1], tc.get("name"),
                         prop.get("value") if prop is not None else "", outcome, float(tc.get("time", 0))))
            totals.setdefault(suite, {"PASS": 0, "FAIL": 0, "SKIP": 0})[outcome] += 1
ET.ElementTree(merged).write(os.path.join(OUT, "tests_junit.xml"), encoding="utf-8", xml_declaration=True)

stamp = time.strftime("%Y-%m-%d %H:%M:%S")
failed = [r for r in rows if r[4] == "FAIL"]
summary = [f"Test run {stamp}"]
for suite, t in totals.items():
    summary.append(f"  {suite:<12} {t['PASS']} passed, {t['FAIL']} failed, {t['SKIP']} skipped")
summary.append(f"  total        {len(rows) - len(failed)} of {len(rows)} passed")
summary += [f"  FAILED {s}/{f}::{n}" for s, f, n, _, _, _ in failed]
text = "\n".join(summary)
print(text)
with open(os.path.join(OUT, "tests_summary.txt"), "w") as f:
    f.write(text + "\n")

plan = ["# Test plan", "",
        "Generated by `tests/report.py` from the last run of `./run_tests.sh` (do not edit by hand).",
        "Criterion = the docstring of the test. Parametrized tests have one row per case.", "",
        f"Last run: {stamp}. " + ", ".join(f"{s}: {t['PASS']} passed, {t['FAIL']} failed" for s, t in totals.items()) + ".", "",
        "| Suite | File | Test | Acceptance criterion | Last result |", "|---|---|---|---|---|"]
for suite, file, name, criterion, outcome, _ in rows:
    plan.append(f"| {suite} | {file} | `{name}` | {criterion} | {outcome} |")
with open(os.path.join(ROOT, "docs", "test_plan.md"), "w") as f:
    f.write("\n".join(plan) + "\n")
sys.exit(1 if failed else 0)
